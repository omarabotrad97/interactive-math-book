  function buildLesson2Session(nodeId, opts) {
    const node = L2_NODES[nodeId];
    if (!node) return null;
    const savedRec = (typeof getLesson2NodeRecord === 'function') ? getLesson2NodeRecord(nodeId) : null;
    const steps = buildStationSteps(nodeId, savedRec);
    if (!steps.length) return null;

    let startIdx = 0;
    if (savedRec && !opts?.forceReset && !opts?.review) {
      const nextIdx = Math.max(0, Math.min(steps.length - 1, Number(savedRec.index) || 0));
      if (savedRec.passed?.size < steps.length) startIdx = nextIdx;
    }
    // Never skip directly to the end if Station 15 hasn't completed all questions or failed
    if (nodeId === 14 && opts?.forceReset) startIdx = 0;

    return {
      lesson: 2,
      mode: 'l2_station',
      nodeId,
      title: node.title,
      points: node.points || 15,
      steps,
      index: startIdx,
      errors: savedRec ? (Number(savedRec.errors) || 0) : 0,
      showHearts: nodeId !== 14,
      remedial: false
    };
  }

  function buildLesson2RemedialSession(unmasteredList, roundNum) {
    const steps = [];
    const round = Math.max(1, Number(roundNum) || 1);
    unmasteredList.forEach(({ skill, label }) => {
      const bank = L2_REMEDIAL_BANK[skill] || [];
      for (let i = 0; i < 2; i++) {
        const q = bank[(round - 1 + i) % bank.length];
        if (!q) continue;
        steps.push({
          kind: 'l2_exit_mcq',
          key: 'l2_rem_' + skill + '_' + round + '_' + i,
          skill,
          skillLabel: label,
          skillTag: 'تدريب علاجي · ' + label,
          prompt: q.q,
          comparePair: q.comparePair || null,
          options: q.options.map(opt => ({ label: opt, value: opt })),
          correctValue: q.correct,
          reason: 'إتقان مهارة «' + label + '» يعتمد على مقارنة عدد المنازل ثم أول اختلاف من اليسار.',
          noHints: true,
          isRemedial: true,
          hasAudio: false
        });
      }
    });

    if (!steps.length) return null;

    return {
      lesson: 2,
      mode: 'l2_remedial',
      nodeId: 14,
      title: 'تدريب المهارات المتبقية',
      points: 40,
      steps,
      index: 0,
      errors: 0,
      showHearts: true,
      remedial: true,
      remedialRound: round,
      remedialResponses: []
    };
  }

