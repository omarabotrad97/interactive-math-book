  function explainComparisonPair(a, b) {
    const sa = String(a);
    const sb = String(b);
    if (sa.length !== sb.length) {
      return 'العدد ' + fmt(a) + ' يتكوّن من ' + ar(sa.length) + ' منازل، بينما العدد ' + fmt(b) + ' يتكوّن من ' + ar(sb.length) + ' منازل؛ والعدد ذو المنازل الأكثر هو الأكبر.';
    }
    const diffIdx = [...sa].findIndex((d, i) => d !== sb[i]);
    if (diffIdx === -1) return 'تطابقت جميع المنازل؛ إذن العددان متساويان تمامًا.';
    const pos = sa.length - 1 - diffIdx;
    return 'أول اختلاف من اليسار في منزلة ' + (PLACE_NAMES_9[pos] || 'العليا') + ': ' + sa[diffIdx] + (a > b ? ' > ' : ' < ') + sb[diffIdx] + '.';
  }

