  function buildLesson4Session(nodeId, opts) {
    const id = Number(nodeId);
    const node = (typeof L4_NODES !== 'undefined' && L4_NODES.find((n) => n.id === id)) || {
      id,
      title: 'الدرس 4: الأعداد السالبة',
      goal: 'إتقان الأعداد السالبة وتمثيلها على خط الأعداد',
      kind: id === 13 ? 'exit_ticket' : 'practice',
      points: id === 13 ? 25 : 15
    };
    const isReplay = Boolean(opts && opts.replay);
    const rec = typeof getLesson4NodeRecord === 'function'
      ? (isReplay && typeof resetLesson4NodeRecordForReplay === 'function'
          ? resetLesson4NodeRecordForReplay(id)
          : getLesson4NodeRecord(id))
      : { index: 0, passed: new Set(), assistedSteps: new Set(), independentSteps: new Set(), errors: 0, data: {} };

    const steps = (STATIONS_STEPS[id] || []).map((st, idx) => Object.assign({}, st, {
      key: st.key || ('l4_n' + id + '_s' + idx),
      stepIndex: idx
    }));
    const startIdx = isReplay ? 0 : Math.min(Math.max(0, Number(rec.index) || 0), Math.max(0, steps.length - 1));

    return {
      lesson: 4,
      nodeId: id,
      node,
      isExitTicket: id === 13,
      isRemedial: false,
      remedial: false,
      title: node.title,
      goal: node.goal || '',
      kind: node.kind || 'practice',
      points: node.points || (id === 13 ? 25 : 15),
      steps,
      index: startIdx,
      passed: new Set(rec.passed || []),
      assistedSteps: new Set(rec.assistedSteps || []),
      independentSteps: new Set(rec.independentSteps || []),
      errors: Number(rec.errors) || 0,
      showHearts: id !== 13
    };
  }

