  function buildLesson5Session(nodeId, opts) {
    const id = Number(nodeId);
    const node = (typeof L5_NODES !== 'undefined' && L5_NODES.find((n) => n.id === id)) || {
      id,
      title: 'الدرس 5: خطة حل المسألة: أنشئ جدولاً',
      goal: 'أحل مسائل حياتية باستعمال خطة إنشاء جدول',
      kind: id === 9 ? 'exit_ticket' : 'practice',
      points: id === 9 ? 20 : 15
    };
    const isReplay = Boolean(opts && opts.replay);
    const rec = typeof getLesson5NodeRecord === 'function'
      ? (isReplay && typeof resetLesson5NodeRecordForReplay === 'function'
          ? resetLesson5NodeRecordForReplay(id)
          : getLesson5NodeRecord(id))
      : { index: 0, passed: new Set(), assistedSteps: new Set(), independentSteps: new Set(), errors: 0, data: {} };

    const steps = (STATIONS_STEPS[id] || []).map((st, idx) => Object.assign({}, st, {
      key: st.key || ('l5_n' + id + '_s' + idx),
      stepIndex: idx
    }));
    const startIdx = isReplay ? 0 : Math.min(Math.max(0, Number(rec.index) || 0), Math.max(0, steps.length - 1));

    return {
      lesson: 5,
      nodeId: id,
      node,
      isExitTicket: id === 9,
      isRemedial: false,
      remedial: false,
      title: node.title,
      goal: node.goal || '',
      kind: node.kind || 'practice',
      points: node.points || (id === 9 ? 20 : 15),
      steps,
      index: startIdx,
      passed: new Set(rec.passed || []),
      assistedSteps: new Set(rec.assistedSteps || []),
      independentSteps: new Set(rec.independentSteps || []),
      errors: Number(rec.errors) || 0,
      showHearts: id !== 9
    };
  }

  function buildLesson5RemedialSession(unmasteredList, roundNum) {
    const rawList = Array.isArray(unmasteredList) && unmasteredList.length
      ? unmasteredList
      : ['l5_understand_plan'];
    const skills = rawList.map((item) => (typeof item === 'string' ? item : item && item.skill)).filter(Boolean);
    const steps = [];
    skills.forEach((sk) => {
      const bank = L5_REMEDIAL_BANK[sk] || [];
      bank.forEach((item, i) => {
        steps.push({
          kind: 'l2_exit_mcq',
          key: 'l5_rem_' + sk + '_' + (roundNum || 1) + '_' + i,
          skill: sk,
          skillTag: 'خطة علاجية (جولة ' + (Number(roundNum) || 1) + ')',
          title: 'تدريب علاجي موجه',
          prompt: item.q,
          options: makeOpts(item.options),
          correctValue: item.correct,
          reason: item.explain || 'أحسنت! أتقنت هذه المهارة.',
          explainRight: item.explain || 'أحسنت! أتقنت هذه المهارة.',
          explainWrong: 'راجع قاعدة الجدول ثم اختر الإجابة الصحيحة.',
          hints: [item.explain || 'تذكّر تنظيم القيم في جدول عمودي منظم.']
        });
      });
    });

    const node = (typeof L5_NODES !== 'undefined' && L5_NODES.find((n) => n.id === 9)) || {
      id: 9,
      title: 'تعزيز المهارات المتبقية - الدرس 5',
      points: 20
    };
    return {
      lesson: 5,
      nodeId: 9,
      node,
      title: 'تعزيز المهارات المتبقية — الجولة ' + (Number(roundNum) || 1),
      goal: 'تقوية المهارات المتبقية ثم إعادة التحقق من بطاقة الإتقان',
      kind: 'remedial',
      points: 20,
      remedial: true,
      isRemedial: true,
      isExitTicket: false,
      remedialSkills: skills,
      remedialRound: Number(roundNum) || 1,
      remedialPassed: new Set(),
      remedialResponses: [],
      steps,
      index: 0,
      passed: new Set(),
      assistedSteps: new Set(),
      independentSteps: new Set(),
      errors: 0,
      showHearts: true
    };
  }

