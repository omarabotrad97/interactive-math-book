  function getStepCount(nodeId) {
    const id = Number(nodeId);
    if (id === 10) return U2L1_MASTERY_QUESTIONS.length;
    return Array.isArray(STATIONS_STEPS[id]) ? STATIONS_STEPS[id].length : 0;
  }

  function buildU2L1Session(nodeId, options) {
    const id = Number(nodeId);
    const node = typeof U2L1_NODES !== 'undefined' ? U2L1_NODES.find((n) => n.id === id) : null;
    if (!node) return null;
    const rawSteps = id === 10 ? U2L1_MASTERY_QUESTIONS : (STATIONS_STEPS[id] || []);
    if (!rawSteps.length) return null;

    const steps = rawSteps.map((st, idx) => ({
      ...st,
      key: st.id || ('u2l1_n' + id + '_s' + idx),
      nodeId: id,
      stepIdx: idx,
      lesson: 7
    }));

    const rec = typeof getU2L1NodeRecord === 'function' ? getU2L1NodeRecord(id) : null;
    let startIdx = 0;
    if (options && options.preserveProgress && rec) {
      const firstUnpassed = steps.findIndex((_, i) => !rec.passed.has(i));
      startIdx = firstUnpassed >= 0 ? firstUnpassed : Math.min(steps.length - 1, Number(rec.index) || 0);
    }

    return {
      lesson: 7,
      mode: id === 10 ? 'u2l1_exit' : 'u2l1_station',
      nodeId: id,
      title: node.title,
      points: node.points || 20,
      showHearts: id !== 10,
      isExitTicket: id === 10,
      remedial: false,
      steps,
      index: startIdx,
      errors: rec ? (Number(rec.errors) || 0) : 0
    };
  }

  function buildU2L1RemedialSession(unmasteredList, roundNum) {
    const list = Array.isArray(unmasteredList) ? unmasteredList : [];
    const steps = [];
    list.forEach((item) => {
      const skillKey = typeof item === 'string' ? item : item.skill;
      const bank = U2L1_REMEDIAL_BANK[skillKey] || [];
      bank.forEach((q, qIdx) => {
        steps.push({
          ...q,
          kind: 'l2_exit_mcq',
          skill: skillKey,
          noHints: true,
          reason: q.explainRight,
          key: 'u2l1_rem_' + skillKey + '_r' + (roundNum || 1) + '_' + qIdx,
          remedialSkill: skillKey,
          lesson: 7,
          nodeId: 10
        });
      });
    });
    if (!steps.length) return null;
    return {
      lesson: 7,
      mode: 'u2l1_remedial',
      kind: 'remedial',
      nodeId: 10,
      title: 'تدريب علاجي لمهارات الضرب الذهني',
      points: 0,
      showHearts: true,
      remedial: true,
      isRemedial: true,
      remedialRound: roundNum || 1,
      remedialPassed: new Set(),
      remedialResponses: [],
      steps,
      index: 0,
      errors: 0
    };
  }

  return {
    U2L1_SKILLS,
    U2L1_MASTERY_QUESTIONS,
    U2L1_REMEDIAL_BANK,
    getStepCount,
    buildU2L1Session,
    buildU2L1RemedialSession
  };
